import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDocument } from '../dist/esm/src/openapi/index.js';
import { routes } from '../dist/esm/src/features/routes.js';

// ─────────────────────────────────────────────────────────────────────
// Paths
//
// The script lives at src/scripts/, so the package root is two levels
// up. `process.chdir` anchors cwd so relative paths (schema.json,
// package.json) resolve as they would from the package root, and so
// any internal lookups by the OpenAPI builder that assume cwd land in
// the right place.
// ─────────────────────────────────────────────────────────────────────

const here = dirname(fileURLToPath(import.meta.url));
process.chdir(resolve(here, '../'));

const SCHEMA_PATH = 'dist/assets/schema.json';
const OUTPUT_PATH = 'dist/assets/openapi-specs.json';
const PKG_MANIFEST = 'package.json';

async function main() {
  // ───────────────────────────────────────────────────────────────────
  // 1. Read inputs
  //
  // - schema.json — generated by src/scripts/gen-json-schema.js.
  //   Provides the `definitions` map that populates
  //   `components.schemas` and resolves every `$ref` in the routes'
  //   request/response schemas.
  //
  // - package.json — for the version string in `info.version`.
  // ───────────────────────────────────────────────────────────────────

  let schemaDoc;
  try {
    schemaDoc = JSON.parse(await readFile(SCHEMA_PATH, 'utf8'));
  } catch (err) {
    throw new Error(
      `Could not read ${SCHEMA_PATH}. Run 'pnpm gen:json-schema' first.\n` +
        `Underlying error: ${err.message}`,
      { cause: err },
    );
  }

  const pkg = JSON.parse(await readFile(PKG_MANIFEST, 'utf8'));

  // ───────────────────────────────────────────────────────────────────
  // 2. Compose the document
  //
  // `routes` is imported from the source feature table, not from
  // `dist/features/routes.js`. Under tsx this resolves the TypeScript
  // source directly, so the script runs on a fresh clone without a
  // prior build — the module graph is identical at runtime (types are
  // erased, handler references are stable), and the OpenAPI document
  // is the same either way.
  //
  // `basePath` defaults to '/' but is overridable via `API_BASE_PATH`
  // for deployments that need to describe the API under a sub-path.
  // ───────────────────────────────────────────────────────────────────

  const basePath = process.env.API_BASE_PATH ?? '/';

  const document = buildDocument(routes, {
    basePath,
    version: pkg.version,
    definitions: schemaDoc.definitions ?? {},
  });

  // ───────────────────────────────────────────────────────────────────
  // 3. Write
  //
  // Pretty-printed so the file is diffable in code review — schema
  // changes show up as readable hunks instead of one-line JSON blobs.
  // ───────────────────────────────────────────────────────────────────

  await mkdir('dist/assets', { recursive: true });
  await writeFile(
    OUTPUT_PATH,
    `${JSON.stringify(document, null, 2)}\n`,
    'utf8',
  );

  const pathCount = Object.keys(document.paths ?? {}).length;
  const schemaCount = Object.keys(document.components?.schemas ?? {}).length;

  console.log(
    `✅ OpenAPI spec written to ${OUTPUT_PATH}\n` +
      `   Paths: ${pathCount}\n` +
      `   Components: ${schemaCount}`,
  );
}

main().catch((err) => {
  console.error('❌ OpenAPI generation failed:\n');
  console.error(err);
  process.exit(1);
});
