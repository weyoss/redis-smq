import { ERedisConfigClient, net } from 'redis-smq-common';
import { type IApiConfig, RedisSMQRestApi } from 'redis-smq-rest-api';

/**
 * A running standalone `RedisSMQRestApi` instance.
 *
 * Used by `api-proxy.test.ts` and `cli.test.ts` as an upstream for the
 * web server to proxy to. It is not used by the shared setup — the web
 * server's own embedded REST API is not constructed through this
 * helper, because the embedded API is a configuration of the web
 * server, not a separate process.
 */
export interface ApiInstance {
  /** Base URL, e.g. `http://127.0.0.1:54321`. */
  url: string;

  /** The underlying instance, for tests that need the Koa callback. */
  api: RedisSMQRestApi;

  /** Stops the HTTP listener and shuts down the REST API's runtime. */
  shutdown(): Promise<void>;
}

export interface StartApiOptions {
  /** Port the embedded Redis is listening on. */
  redisPort: number;

  /**
   * Optional overrides. `apiServer.port` is always regenerated by this
   * helper — callers cannot pin it, because doing so would reintroduce
   * the `EADDRINUSE` race the random port exists to prevent.
   */
  overrides?: Partial<Omit<IApiConfig, 'apiServer'>> & {
    apiServer?: Omit<NonNullable<IApiConfig['apiServer']>, 'port'>;
  };
}

export async function startApi(options: StartApiOptions): Promise<ApiInstance> {
  const { redisPort, overrides = {} } = options;
  const port = await net.getRandomPort();

  const config: IApiConfig = {
    redis: {
      client: ERedisConfigClient.IOREDIS,
      options: { host: '127.0.0.1', port: redisPort },
    },
    ...overrides,
    apiServer: {
      basePath: '/',
      ...overrides.apiServer,
      port,
    },
  };

  const api = new RedisSMQRestApi(config);
  await api.run();

  return {
    url: `http://127.0.0.1:${port}`,
    api,
    shutdown: () => api.shutdown(),
  };
}
